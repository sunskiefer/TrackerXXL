#!/usr/bin/env python3
"""Generate bazz/bass_bank.h: LXRXXL BAZZLINE's eight factory bass sounds (bazz/src/factory.c, SOUNDS[8]) written as
LXRXXL ZYNTH sound-parameter sets for ZYNTH's BAZZ voice (ENG_BAZZ), the voice that carries BAZZLINE's oscillator and
chain inside the voice library.

Mapping of BAZZLINE's 37 sound parameters to ZYNTH's (zynth/src/ids.h):
  * same name, same meaning: DRIVE SPREAD VCA_DEC VCF_ENV RESO CUTOFF FM SUB NOISE LFO_RATE LFO_LVL PITCH_AMT WAVE FMODE
    FM_RATIO DRIVE_POS CURVE ACC_AMT ACC_SWEEP SLIDE VCF_ATK VCF_DEC VCA_ATK PITCH_DEC LEVEL PAN FMODEL KEYTRACK SW_MODE
    SW_RATE SW_MIX MOD_WAVE MOD_DEST MOD_SYNC
  * OSC_MODE (VCO / FM / WAVE)  -> SP_V1  (ZYNTH BAZZ's OSC MODE slider is a 3-zone stepped slider: option m = (m+.5)/3)
  * WAVE_POS                    -> SP_V2  (WAVE POS)
  * TONE                        -> SP_V6  (TONE)
ZYNTH-only controls are set so the voice behaves as BAZZLINE's did (voice.c, BAZZLINE: no drift, a -1 octave square sub,
no second oscillator, no fold / crush / saturate): V3 OCTAVE centre, V4 SUB OCT -1, V5 DRIFT 0, V7 OSC 2 LEVEL 0, V8 .2,
V9 OSC 2 OCTAVE centre, V10..V12 0, and, when BAZZLINE's VCA ENV is fully down (VCA follows the gate, 8 ms release), SUSTAIN 1
and RELEASE .3 (relSeconds*.25 = 8 ms), else SUSTAIN 0 (the note decays on its own, as in BAZZLINE).
Every value not named in factory.c is BAZZLINE's default (bazz/src/param_map.h SOUND_DEFS).
"""
import re, sys, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
fac = (root / "bazz/src/factory.c").read_text()
pm = (root / "bazz/src/param_map.h").read_text()
ids = (root / "bazz/src/ids.h").read_text()

sp_order = re.findall(r"^\s+(SP_[A-Z0-9_]+),?$", ids.split("enum {")[1].split("};")[0], re.M)
sp_order = [s for s in sp_order if s != "SP_COUNT"]
defs_block = pm.split("static const SoundDef SOUND_DEFS[]")[1].split("};")[0]
defs = [float(m) for m in re.findall(r'\{"[a-z_0-9]+", "[^"]+", (-?[0-9.]+)f', defs_block)]
assert len(defs) == len(sp_order), (len(defs), len(sp_order))
default = dict(zip(sp_order, defs))

rows = fac.split("static const Set SOUNDS[NUM_TRACKS][24] = {")[1].split("\n};")[0]
sounds = []
for chunk in re.findall(r"\{\{(SP_.*?)END\}", rows, re.S):
    d = {}
    for k, v in re.findall(r"(SP_[A-Z0-9_]+), ([^}]+)\}", chunk):
        d[k] = float(eval(re.sub(r"([0-9.])f\b", r"\1", v.strip()), {}, {}))
    sounds.append(d)
assert len(sounds) == 8, len(sounds)

# names from the header comment of factory.c: "1 ACID ... 2 DB-01 style ..." (two columns)
NAMES = ["ACID", "DB-01", "REESE", "SUB", "FM GROWL", "808", "PLUCK", "WAVE"]
assert "ACID" in fac and "REESE" in fac and "808" in fac and "PLUCK" in fac

MAP_SAME = [s for s in sp_order if s not in ("SP_OSC_MODE", "SP_WAVE_POS", "SP_TONE")]
out = []
out.append("/* GENERATED by tools/gen_bass_bank.py from bazz/src/factory.c (LXRXXL BAZZLINE f47ebb6): do not edit.\n"
           " * BAZZLINE's eight factory bass sounds as ZYNTH BAZZ-voice parameter sets (see the script for the mapping). */")
out.append("#define BASS_BANK_N %d" % len(sounds))
out.append("static const char *const BASS_BANK_NAMES[BASS_BANK_N] = {%s};" % ", ".join('"%s"' % n for n in NAMES))
out.append("typedef struct { uint8_t sp; float v; } BassSet;")
out.append("#define BASS_BANK_SETS 52")
out.append("static const BassSet BASS_BANK[BASS_BANK_N][BASS_BANK_SETS] = {")
for i, snd in enumerate(sounds):
    val = {k: default[k] for k in sp_order}
    val.update(snd)
    sets = []
    for k in MAP_SAME:
        sets.append((k, val[k]))
    sets.append(("SP_V1", (val["SP_OSC_MODE"] + 0.5) / 3.0))
    sets.append(("SP_V2", val["SP_WAVE_POS"]))
    sets.append(("SP_V6", val["SP_TONE"]))
    sets += [("SP_V3", 0.5), ("SP_V4", 0.25), ("SP_V5", 0.0), ("SP_V7", 0.0), ("SP_V8", 0.2), ("SP_V9", 0.5),
             ("SP_V10", 0.0), ("SP_V11", 0.0), ("SP_V12", 0.0)]
    gated = val["SP_VCA_DEC"] <= 0.02
    sets += [("SP_SUSTAIN", 1.0 if gated else 0.0), ("SP_VCA_REL", 0.3 if gated else 0.2), ("SP_VCF_SUS", 0.0),
             ("SP_VCF_REL", 0.3)]
    assert len(sets) < 52, len(sets)
    body = ", ".join("{%s, %.6ff}" % (k, v) for k, v in sets)
    out.append("    /* %d %s */ {%s, {255, 0.f}}," % (i + 1, NAMES[i], body))
out.append("};")
(root / "bazz/bass_bank.h").write_text("\n".join(out) + "\n")
print("wrote bazz/bass_bank.h:", len(sounds), "sounds")
