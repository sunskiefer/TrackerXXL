#!/usr/bin/env python3
"""controls.json -> params.json (mpc-vst-plugins format, VST index = list order) and build/ctl_table.h (the engine's table).
Usage: gen_controls.py <platform dir>"""
import json, os, sys

root = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
spec = json.load(open(os.path.join(root, "controls.json")))
params, rows, keys = [], [], set()
KIND = {"relative": "CT_REL", "clicks": "CT_CLICKS", "button": "CT_BTN", "virtual": "CT_VIRT", "pad": "CT_PAD", "option": "CT_OPT"}
btn_index = {}
for sec in spec["sections"]:
    for c in sec["controls"]:
        if c["type"] == "button":
            btn_index[c["key"]] = c["index"]
for sec in spec["sections"]:
    for c in sec["controls"]:
        k = c["key"]
        assert k not in keys, k
        keys.add(k)
        t = c["type"]
        p = {"key": k, "name": c["name"]}
        a = b = 0
        extra = ""
        if t == "relative":
            p.update(min=0, max=1, default=0.5)
            a = int(c["clicks_per_unit"])
            role = c.get("role", "wheel")
            if role in ("focus_h", "focus_v"):
                a = int(c["clicks_per_unit"])
                b = btn_index[c["pos_button"]] * 256 + btn_index[c["neg_button"]]
            extra = {"wheel": "ROLE_WHEEL", "value_fine": "ROLE_VALUE", "value_coarse": "ROLE_VALUE_COARSE", "focus_h": "ROLE_FOCUS", "focus_v": "ROLE_FOCUS"}[role]
        elif t == "clicks":
            p.update(min=0, max=1, default=0, momentary=True)
            a = int(c["clicks"])
        elif t == "button":
            p.update(min=0, max=1, default=0)
            if c["kind"] == "trigger":
                p["momentary"] = True
            a = c["index"]
            b = 1 if c["kind"] == "latch" else 0
        elif t == "virtual":
            p.update(min=0, max=1, default=0, momentary=True)
            extra = {"stop": "VIRT_STOP"}[c["action"]]
        elif t == "pad":
            p.update(min=0, max=1, default=0, momentary=True)
            a = c["n"]
        elif t == "option":
            p.update(options=c["options"], default=c["default"])
            extra = {"pad_cols": "OPT_PAD_COLS", "host_sync": "OPT_HOST_SYNC"}[c["action"]]
        params.append(p)
        rows.append('    {"%s", %s, %d, %d, %s},' % (k, KIND[t], a, b, extra or "0"))
sections = [{"label": s["label"], "keys": [c["key"] for c in s["controls"]]} for s in spec["sections"]]
json.dump({"params": params, "sections": sections}, open(os.path.join(root, "params.json"), "w"), indent=1)
os.makedirs(os.path.join(root, "build"), exist_ok=True)
with open(os.path.join(root, "build", "ctl_table.h"), "w") as f:
    f.write("/* generated by tools/gen_controls.py from controls.json: do not edit */\n#pragma once\n")
    f.write("#define CTL_TAP_MS %d\n#define CTL_PAD_NOTE_BASE %d\n#define CTL_PAD_NOTE_COUNT %d\n" % (spec["tap_ms"], spec["pad_note_base"], spec["pad_note_count"]))
    f.write("enum { CT_REL, CT_CLICKS, CT_BTN, CT_VIRT, CT_PAD, CT_OPT };\n")
    f.write("enum { ROLE_NONE, ROLE_WHEEL, ROLE_VALUE, ROLE_VALUE_COARSE, ROLE_FOCUS };\nenum { VIRT_STOP = 1 };\nenum { OPT_PAD_COLS = 1, OPT_HOST_SYNC };\n")
    f.write("typedef struct { const char *key; int type; int a; int b; int x; } ctl_t;\n")
    f.write("static const ctl_t CTLS[] = {\n" + "\n".join(rows) + "\n};\n#define NCTLS %d\n" % len(rows))
print("controls: %d parameters" % len(params))
# compile-time check that every button index in controls.json is the firmware's enum value
with open(os.path.join(root, "build", "ctl_check.h"), "w") as f:
    f.write("/* generated by tools/gen_controls.py: include after core/interface/core/interfaceDefs.h */\n")
    for sec in spec["sections"]:
        for c in sec["controls"]:
            if c["type"] == "button":
                f.write('static_assert((int)%s == %d, "controls.json: %s does not match the firmware enum");\n' % (c["fw"], c["index"], c["key"]))
